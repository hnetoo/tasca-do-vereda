
const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');
const path = require('path');

// Load env vars from .env.local manually
const envPath = path.resolve(process.cwd(), '.env.local');
let supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
let supabaseKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (fs.existsSync(envPath)) {
  const envConfig = fs.readFileSync(envPath, 'utf8');
  envConfig.split('\n').forEach(line => {
    const [key, value] = line.split('=');
    if (key && value) {
      if (key.trim() === 'NEXT_PUBLIC_SUPABASE_URL') supabaseUrl = value.trim().replace(/"/g, '');
      if (key.trim() === 'NEXT_PUBLIC_SUPABASE_ANON_KEY') supabaseKey = value.trim().replace(/"/g, '');
    }
  });
}

if (!supabaseUrl || !supabaseKey) {
  console.error('Missing Supabase URL or Key');
  process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

async function insertTestProduct() {
  console.log('Connecting to Supabase...');
  
  // 1. Get a category ID
  const { data: categories, error: catError } = await supabase
    .from('categories')
    .select('id, name')
    .limit(1);

  if (catError) {
    console.error('Error fetching categories:', catError);
    return;
  }

  if (!categories || categories.length === 0) {
    console.error('No categories found. Cannot insert product without category.');
    return;
  }

  const category = categories[0];
  console.log(`Using category: ${category.name} (${category.id})`);

  // 2. Insert product
  const testProduct = {
    name: `Test Product Realtime ${new Date().toLocaleTimeString()}`,
    description: 'Generated by automated test script to verify realtime updates',
    price: 12.99,
    category_id: category.id,
    image_url: 'https://images.unsplash.com/photo-1546069901-ba9599a7e63c', // Valid image URL
    is_available_on_digital_menu: true,
    is_active: true,
    preparation_time: 15,
    tax_code: 'NOR',
    tax_percentage: 23
  };

  const { data, error } = await supabase
    .from('products')
    .insert(testProduct)
    .select()
    .single();

  if (error) {
    console.error('Error inserting product:', error);
  } else {
    console.log('✅ Product inserted successfully!');
    console.log('Product ID:', data.id);
    console.log('Name:', data.name);
    console.log('\n--> Please check the Vercel deployment /menu to see if this product appears automatically.');
  }
}

insertTestProduct();
